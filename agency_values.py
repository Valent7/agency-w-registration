def render_roadmap():
    st.markdown("## 🛤️ Дорожная карта Агентства W")
    st.caption(
        "Живая карта развития. Здесь команда видит, что уже работает, "
        "что мы тестируем сейчас и что будет следующим."
    )

    legend = st.columns(5)
    for col, text in zip(
        legend,
        ["✅ Работает", "🧪 Тестируем", "🔧 Развиваем", "⏭ Следующее", "💡 В планах"],
    ):
        col.markdown(f"**{text}**")

    st.markdown("---")

    for icon, status, title, description in ROADMAP:
        with st.container(border=True):
            left, right = st.columns([1, 5])
            left.markdown(f"## {icon}")
            right.markdown(f"### {title}")
            right.caption(status)
            right.write(description)

    st.markdown("---")
    st.caption(
        "Дорожная карта показывает направление развития, а не обещание конкретной даты. "
        "Приоритет получает то, что сильнее возвращает человеку время, помогает получить "
        "результат и делает работу Агентства удобнее для человека."
    )


