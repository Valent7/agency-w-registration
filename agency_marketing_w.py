"""Маркетинг Агентства W: собственная этичная воронка без стороннего бренда."""
import streamlit as st
from agency_w_partner_plan import render_w_partner_plan


STAGES = (
    ("🎯 Портрет человека", "Определите, кому мешает рутина и какие задачи он хотел бы передать ИИ.", "🤖 Агенты"),
    ("🔎 Поиск и проверка", "Неония ищет релевантные контакты; каждый профиль и право на общение проверяются вручную.", "🤖 Агенты"),
    ("💬 Первое касание", "Неона готовит личное сообщение по конкретной ситуации, но отправку контролирует владелец.", "🤖 Агенты"),
    ("🤝 Содержательный разговор", "Ответить на вопросы, выяснить потребность и при интересе предложить встречу.", "🤖 Агенты"),
    ("📅 Встреча", "Показать реальные функции, ограничения и условия; решение остаётся за человеком.", "📅 Календарь"),
    ("🧭 Знакомство с системой", "Помочь с входом и первыми действиями без обещаний дохода и автоматического успеха.", "👥 Команда"),
    ("🎙 Обучение", "Неола сопровождает партнёра по одному шагу и проверяет понимание.", "🤖 Агенты"),
    ("📊 Результат", "Оценить полезные ответы, встречи, активации и качество сопровождения.", "☀️ День"),
)


def _draft(audience, problem, channel, purpose):
    audience = audience.strip() or "человека, которому хочется освободить время"
    problem = problem.strip() or "повторяющиеся рабочие задачи"
    if purpose == "Приглашение на встречу":
        return (
            f"Здравствуйте! Увидела, что вам близка тема: {problem}. "
            "Мы развиваем Агентство W — цифровую команду, которая помогает "
            "передавать ИИ часть повседневной работы. "
            "Могу показать на короткой встрече, как это устроено на практике. "
            "Вам было бы интересно?"
        )
    if purpose == "Ответ на интерес":
        return (
            f"Спасибо за интерес! Агентство W помогает с поиском подходящих людей, "
            "подготовкой персональных сообщений и организацией первых шагов. "
            "Конкретные возможности зависят от подключённых инструментов. "
            "Удобнее показать на примере — хотите договориться о короткой встрече?"
        )
    return (
        f"Здравствуйте! Обратила внимание на вашу сферу — {audience}. "
        f"Скажите, знакома ли вам ситуация, когда {problem} отнимают слишком много времени? "
        "В Агентстве W мы исследуем, как передать такие задачи цифровым сотрудникам. "
        "Если тема вам близка, могу показать пример."
    )


def render_marketing_w(owner_name: str):
    st.markdown("## 📣 Маркетинг Агентства W")
    st.caption("Продвижение продуктов, развитие партнёрской сети, мотивация и обучение команды W.")
    st.info(
        "Наш принцип: человек понимает пользу → добровольно проявляет интерес → "
        "принимает решение. ИИ сокращает рутину, решения остаются за людьми."
    )

    partner_plan, route, outreach, measurement = st.tabs(
        ["🌳 Партнёрский план", "🧭 Маршрут", "✉️ Личное приглашение", "📈 Результаты"]
    )

    with partner_plan:
        render_w_partner_plan()

    with route:
        st.markdown("### Единый путь от интереса до результата")
        for idx, (title, explanation, target) in enumerate(STAGES, 1):
            with st.expander(f"{idx}. {title}", expanded=idx == 1):
                st.write(explanation)
                st.caption(f"Связанный раздел Агентства: {target}")
                if st.button("Открыть связанный раздел", key=f"w_marketing_stage_{idx}"):
                    st.session_state["agency_open_main_section"] = target
                    st.rerun()
        st.markdown("**Не делаем:** массовых холодных рассылок, давления, искусственного дефицита, "
                    "недоказанных обещаний и автоматической отправки без согласования.")

    with outreach:
        st.markdown("### Черновик под конкретного человека")
        st.caption("Текст остаётся внутри кабинета и никуда не отправляется автоматически.")
        audience = st.text_input(
            "Кому пишем — профессия или интерес",
            placeholder="Например: специалист, ведущий консультации",
            key="w_marketing_audience",
        )
        problem = st.text_input(
            "Что забирает его время",
            placeholder="Например: переписка, поиск клиентов и записи",
            key="w_marketing_problem",
        )
        channel = st.selectbox(
            "Площадка", ["Telegram", "VK", "Instagram — комментарий вручную", "Другой канал"],
            key="w_marketing_channel",
        )
        purpose = st.radio(
            "Цель", ["Начать разговор", "Ответ на интерес", "Приглашение на встречу"],
            horizontal=True, key="w_marketing_purpose",
        )
        if st.button("Подготовить черновик", type="primary", key="w_marketing_make"):
            st.session_state["w_marketing_draft"] = _draft(audience, problem, channel, purpose)
        if st.session_state.get("w_marketing_draft"):
            st.text_area(
                "Проверьте и отредактируйте перед использованием",
                key="w_marketing_draft",
                height=175,
            )
            st.caption("Используйте только при допустимом контакте; не выдавайте черновик за личное знакомство.")
        st.markdown("**Что показать вместо обещаний:** короткий ролик о работе цифровой команды, "
                    "реальную демонстрацию или встречу с владельцем аккаунта.")

    with measurement:
        st.markdown("### Контроль качества работы")
        st.caption("Введите фактические результаты за выбранный период. Это локальный расчёт на экране, не база CRM.")
        col1, col2, col3 = st.columns(3)
        with col1:
            checked = st.number_input("Проверено профилей", min_value=0, step=1, key="w_market_checked")
            reached = st.number_input("Личных обращений", min_value=0, step=1, key="w_market_reached")
        with col2:
            answers = st.number_input("Содержательных ответов", min_value=0, step=1, key="w_market_answers")
            meetings = st.number_input("Проведённых встреч", min_value=0, step=1, key="w_market_meetings")
        with col3:
            starts = st.number_input("Начали пользоваться", min_value=0, step=1, key="w_market_starts")
            costs = st.number_input("Затраты, €", min_value=0.0, step=1.0, key="w_market_costs")
        a, b, c = st.columns(3)
        a.metric("Ответы / обращения", f"{answers / reached * 100:.1f}%" if reached else "—")
        b.metric("Встречи / ответы", f"{meetings / answers * 100:.1f}%" if answers else "—")
        c.metric("Стоимость начала работы", f"{costs / starts:.2f} €" if starts else "—")
        if answers > reached or meetings > answers or starts > meetings:
            st.warning("Проверьте числа: показатели этапов могут относиться к разным периодам.")
        st.caption(
            "Для точного учёта кандидатов, диалогов и встреч используйте рабочие разделы "
            "Неонии, Неоны и Календаря."
        )
