def competitor_prompt_block(text: str) -> str:
    normalized = _normalize(text)
    aliases = {
        "sintra": ("sintra", "синтра"),
        "artisan": ("artisan", "ava", "артизан", "ава"),
        "o-key": ("o-key", "okey", "o key", "о-кей", "окей"),
        "aibox": ("myaibox", "ai box", "aibox", "аибокс", "аи бокс"),
    }
    key = next(
        (name for name, variants in aliases.items() if any(_contains_phrase(text, v) for v in variants)),
        None,
    )
    if not key:
        return (
            "Конкурент не опознан по проверенной карточке. Не выдумывай сравнение. "
            "Спроси, что именно этот сервис уже делает для человека, и сравнивай только после появления подтверждённых фактов."
        )

    card = COMPETITOR_CARDS[key]
    if card["status"] != "verified":
        return (
            f"Упомянут {card['name']}, но карточка пока не подтверждена. "
            f"{card['w_difference']}"
        )

    facts = "\n".join(f"- {fact}" for fact in card["facts"])
    return (
        f"Проверенная карточка конкурента: {card['name']} (проверено {card['checked_at']}).\n"
        f"Подтверждённые факты:\n{facts}\n"
        f"Как корректно показать отличие W: {card['w_difference']}\n"
        "Не перечисляй всё сразу: используй максимум ОДИН факт, связанный с вопросом человека."
    )
