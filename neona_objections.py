def _normalize(text: str) -> str:
    raw = str(text or "").lower().replace("ё", "е")
    raw = re.sub(r"[^a-zа-я0-9]+", " ", raw)
    return re.sub(r"\s+", " ", raw).strip()


def _contains_phrase(text: str, phrase: str) -> bool:
    normalized = _normalize(text)
    token = _normalize(phrase)
    if not token:
        return False
    pattern = r"(?<!\w)" + re.escape(token).replace(r"\ ", r"\s+") + r"(?!\w)"
    return bool(re.search(pattern, normalized, flags=re.I))


def is_hard_stop(text: str) -> bool:
    normalized = _normalize(text)
    return any(re.search(pattern, normalized, flags=re.I) for pattern in HARD_STOP_PATTERNS)


def _objection_category(text: str) -> dict[str, Any] | None:
    for item in OBJECTION_CATEGORIES:
        if any(_contains_phrase(text, token) for token in item.get("patterns", ())):
            return item
    return None


def classify_neona_reply(text: str) -> dict[str, Any]:
    """Мягкая детерминированная классификация без дополнительного вызова OpenAI."""

    raw = str(text or "").strip()
    normalized = _normalize(raw)

    if is_hard_stop(raw):
        return {
            "kind": "hard_stop",
            "category": "hard_stop",
            "title": "Явная просьба прекратить контакт",
        }

    objection = _objection_category(raw)
    if objection:
        return {
            "kind": "objection",
            "category": str(objection["id"]),
            "title": str(objection["title"]),
            "knowledge": objection,
        }

    if any(_contains_phrase(raw, marker) for marker in POSITIVE_MARKERS):
        return {"kind": "interest", "category": "interest", "title": "Явный интерес"}

    # Вопрос — если есть вопросительный знак либо типичный вопросительный оборот.
    if "?" in raw or re.search(
        r"\b(что|как|зачем|почему|сколько|когда|где|какой|какая|какие|чем|можно ли|кто)\b",
        normalized,
    ):
        return {"kind": "question", "category": "question", "title": "Вопрос"}

    return {"kind": "other", "category": "other", "title": "Обычный ответ"}


