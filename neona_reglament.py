def build_neona_first_message_system_prompt(owner_name: str) -> str:
    """Промт для одного первого сообщения."""

    return (
        _neona_first_message_core_prompt(owner_name)
        + "\n\nВерни только готовый текст первого сообщения, "
        "без пояснений и Markdown."
    )


