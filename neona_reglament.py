def owner_name_genitive(owner_name: str) -> str:
    """Склоняет обычное русское имя владельца в родительный падеж.

    Для нестандартных имён лучше в будущем хранить отдельное поле
    `name_genitive` в профиле. Здесь покрыты наиболее частые варианты.
    """

    name = str(owner_name or "").strip()
    if not name:
        return "владельца кабинета"

    exceptions = {
        "Любовь": "Любови",
        "Надежда": "Надежды",
        "Валентина": "Валентины",
        "Эльза": "Эльзы",
        "Любовь": "Любови",
        "Ольга": "Ольги",
        "Мария": "Марии",
        "Наталья": "Натальи",
        "София": "Софии",
    }
    if name in exceptions:
        return exceptions[name]

    lowered = name.lower()
    if lowered.endswith("ия"):
        return name[:-1] + "и"
    if lowered.endswith("я"):
        return name[:-1] + "и"
    if lowered.endswith("а"):
        previous = lowered[-2:-1]
        ending = "и" if previous in "гкхжчшщц" else "ы"
        return name[:-1] + ending
    if lowered.endswith("ь"):
        return name[:-1] + "и"
    if lowered.endswith("й"):
        return name[:-1] + "я"
    if lowered[-1:] in "бвгджзклмнпрстфхцчшщ":
        return name + "а"

    return name



def choose_neona_magnet(contact: dict) -> str:
    """Выбирает один человеческий магнит по доступному безопасному контексту."""

    contact = contact or {}
    public_messages = contact.get("public_messages") or []
    public_text = " ".join(
        str(item.get("text") if isinstance(item, dict) else item)
        for item in public_messages[:5]
    )

    haystack = " ".join(
        str(contact.get(key) or "")
        for key in (
            "segment",
            "message_angle",
            "profile_about",
            "source",
            "familiarity_note",
            "owner_draft",
            "must_mention",
        )
    )
    haystack += " " + " ".join(
        str(item) for item in (contact.get("reasons") or [])
    )
    haystack += " " + public_text
    lowered = haystack.lower()

    # Лидер/наставник/команда: сильнее всего боль постоянного сопровождения людей.
    if any(token in lowered for token in (
        "лидер", "настав", "команд", "организатор", "руковод",
        "обучен", "онбординг", "нович", "mlm", "сетев"
    )):
        return "Новичок не остаётся один"

    # Уже есть собственное направление/бизнес/проект.
    if any(token in lowered for token in (
        "свой проект", "проект", "бизнес", "предприним",
        "партнёрск", "компания", "бренд"
    )):
        return "Не менять свой проект — усилить его"

    # Контакты / поиск людей / рекрутинг.
    if any(token in lowered for token in (
        "контакт", "telegram", "телеграм", "рекрут",
        "поиск людей", "знаком", "нетворк", "network"
    )):
        return "Не писать всем подряд — начать с подходящих людей"

    # Технологии / голос / простота ИИ.
    if any(token in lowered for token in (
        "голос", "технолог", "нейросет", "искусственн", "chatgpt",
        "чатгпт", "ai ", " ии ", "автоматизац"
    )):
        return "ИИ не нужно изучать — можно просто спросить голосом"

    # Нагрузка и нехватка времени.
    if any(token in lowered for token in (
        "занят", "время", "рутин", "нагруз", "много задач",
        "мероприят", "организац"
    )):
        return "Вернуть себе время"

    # Обучение и школы.
    if any(token in lowered for token in (
        "курс", "школ", "обучение", "тренинг", "вебинар"
    )):
        return "Не ещё одна школа — реальная помощь в работе"

    return "Своя ИИ-команда рядом"


def neona_identity(owner_name: str) -> str:
    """Возвращает утверждённое простое представление Неоны."""

    owner = owner_name_genitive(owner_name)
    return f"Меня зовут Неона, я секретарь-референт {owner}."


