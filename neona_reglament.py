def owner_name_genitive(owner_name: str) -> str:
    name = str(owner_name or "").strip()
    if not name:
        return "владельца кабинета"
    known = {
        "Валентина": "Валентины", "Valentina": "Валентины", "Walentina": "Валентины",
        "Наталья": "Натальи", "Мария": "Марии", "Ольга": "Ольги",
        "Надежда": "Надежды", "Любовь": "Любови",
    }
    if name in known:
        return known[name]
    low = name.lower()
    if low.endswith("ия") or low.endswith("я"):
        return name[:-1] + "и"
    if low.endswith("а"):
        prev = low[-2:-1]
        return name[:-1] + ("и" if prev in "гкхжчшщц" else "ы")
    if low.endswith("й"):
        return name[:-1] + "я"
    if low.endswith("ь"):
        return name[:-1] + "и"
    return name + "а" if low[-1:] in "бвгджзклмнпрстфхцчшщ" else name


