def choose_neona_magnet(contact: dict) -> str:
    """Внутренний выбор для UI. Клиент название магнита не видит."""
    contact = contact or {}
    manual = str(contact.get("selected_magnet_override") or contact.get("manual_magnet") or "").strip()
    if manual in NEONA_MAGNET_NAMES:
        return manual
    public_messages = contact.get("public_messages") or []
    public_text = " ".join(
        str(x.get("text") if isinstance(x, dict) else x)
        for x in public_messages[:5]
    )
    hay = " ".join(
        str(contact.get(k) or "")
        for k in ("segment", "message_angle", "profile_about", "source",
                  "familiarity_note", "owner_draft", "must_mention", "short_portrait")
    )
    hay += " " + " ".join(str(x) for x in (contact.get("reasons") or [])) + " " + public_text
    low = hay.casefold()
    if any(x in low for x in ("время", "рутин", "переписк", "не успева", "занят")):
        return "Вернуть человеку время"
    if any(x in low for x in ("команд", "mlm", "сетев", "партнер", "партнёр", "бизнес", "предприним")):
        return "Усилить существующий проект"
    if any(x in low for x in ("клиент", "людей", "поиск", "рекрут", "контакт")):
        return "Найти подходящих людей"
    return "Вернуть человеку время"


