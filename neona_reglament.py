def build_neona_first_message_system_prompt(owner_name: str) -> str:
    """Промт для одного первого сообщения."""

    return (
        _neona_first_message_core_prompt(owner_name)
        + "\n\nВерни только готовый текст первого сообщения, "
        "без пояснений и Markdown."
    )


def build_neona_first_messages_system_prompt(owner_name: str) -> str:
    """Промт для пакета первых сообщений выбранным кандидатам."""

    return (
        _neona_first_message_core_prompt(owner_name)
        + """

Верни ТОЛЬКО JSON-массив без пояснений и Markdown:
[
  {
    "telegram_id": 123,
    "message": "готовый текст"
  }
]
Для каждого переданного кандидата верни ровно один объект с тем же telegram_id.
""".rstrip()
    )


