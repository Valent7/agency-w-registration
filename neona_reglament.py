def owner_name_genitive(owner_name: str) -> str:
    """Склоняет обычное русское имя владельца в родительный падеж.

    Для нестандартных имён лучше в будущем хранить отдельное поле
    `name_genitive` в профиле. Здесь покрыты наиболее частые варианты.
    """

    name = str(owner_name or "").strip()
    if not name:
        return "владельца кабинета"

    exceptions = {
        "Любовь": "Любови",
        "Надежда": "Надежды",
        "Валентина": "Валентины",
        "Valentina": "Валентины",
        "Walentina": "Валентины",
        "Эльза": "Эльзы",
        "Любовь": "Любови",
        "Ольга": "Ольги",
        "Мария": "Марии",
        "Наталья": "Натальи",
        "София": "Софии",
    }
    if name in exceptions:
        return exceptions[name]

    lowered = name.lower()
    if lowered.endswith("ия"):
        return name[:-1] + "и"
    if lowered.endswith("я"):
        return name[:-1] + "и"
    if lowered.endswith("а"):
        previous = lowered[-2:-1]
        ending = "и" if previous in "гкхжчшщц" else "ы"
        return name[:-1] + ending
    if lowered.endswith("ь"):
        return name[:-1] + "и"
    if lowered.endswith("й"):
        return name[:-1] + "я"
    if lowered[-1:] in "бвгджзклмнпрстфхцчшщ":
        return name + "а"

    return name



def choose_neona_magnet(contact: dict) -> str:
    """Выбирает один человеческий магнит; ручной выбор владельца важнее автоматики."""

    contact = contact or {}

    manual_magnet = str(
        contact.get("selected_magnet_override")
        or contact.get("manual_magnet")
        or ""
    ).strip()
    if manual_magnet in NEONA_MAGNET_NAMES:
        return manual_magnet

    public_messages = contact.get("public_messages") or []
    public_text = " ".join(
        str(item.get("text") if isinstance(item, dict) else item)
        for item in public_messages[:5]
    )
    haystack = " ".join(
        str(contact.get(key) or "")
        for key in (
            "segment", "message_angle", "profile_about", "source",
            "familiarity_note", "owner_draft", "must_mention",
        )
    )
    haystack += " " + " ".join(str(item) for item in (contact.get("reasons") or []))
    haystack += " " + public_text
    lowered = haystack.lower()

    # Сначала самые конкретные признаки, затем более общие.
    if any(token in lowered for token in (
        "не хочу навязы", "не умею писать", "холодн", "первое сообщение",
        "что написать", "не люблю продав", "неудобно писать",
    )):
        return "Начать разговор без навязывания"

    if any(token in lowered for token in (
        "нович", "настав", "обучаю команд", "обучение команды", "сопровожд",
        "повторяю одно", "команда теряет", "после регистрации",
    )):
        return "Сопровождение новичка"

    if any(token in lowered for token in (
        "заменит людей", "бездуш", "робот", "машина вместо", "не хочу отдавать ии",
        "важные решения", "живое общение",
    )):
        return "Человек остаётся главным"

    if any(token in lowered for token in (
        "chatgpt", "чатгпт", "всем одно", "одинаково", "знает мой бизнес",
        "знает проект", "персонализац", "контекст проекта",
    )):
        return "Агентство понимает конкретный проект"

    if any(token in lowered for token in (
        "контакт", "кому писать", "где брать людей", "поиск людей", "рекрут",
        "нетворк", "network", "люди не отвеч", "писать всем",
    )):
        return "Найти подходящих людей"

    if any(token in lowered for token in (
        "свой проект", "бизнес", "предприним", "компания", "бренд", "клиент",
        "консультац", "продаж", "mlm", "сетев", "проект",
    )):
        return "Усилить существующий проект"

    if any(token in lowered for token in (
        "занят", "не успева", "время", "рутин", "нагруз", "много задач",
        "всё сам", "все сама", "переписк", "устал",
    )):
        return "Вернуть человеку время"

    return "Своя ИИ-команда"


