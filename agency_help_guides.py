GUIDE_BY_NUMBER = {guide["number"]: guide for guide in GUIDES}


def instruction_index_text() -> str:
    """Единый список для текстовой Неолы, голосовой Неолы и справочника."""
    return "\n".join(
        f"Инструкция № {guide['number']} — {guide['title']}."
        for guide in GUIDES
    )


def find_instruction(query: str):
    """Простой поиск по номеру или теме, без ИИ и доступа к личным данным."""
    q = str(query or "").strip().casefold()
    if not q:
        return list(GUIDES)
    import re
    number = re.search(r"(?:^|(?:№|номер|инструкц(?:ия|ии)?)\s*)(0?[0-7])\b", q)
    if number:
        target = number.group(1).zfill(2)
        if target in GUIDE_BY_NUMBER:
            return [GUIDE_BY_NUMBER[target]]
    return [
        guide for guide in GUIDES
        if q in (
            guide["number"] + " " + guide["title"].casefold() + " "
            + guide["keywords"].casefold() + " " + guide["goal"].casefold()
        )
    ]


def render_builtin_instructions() -> None:
    """Показывает один и тот же справочник всем пользователям Агентства."""
    import streamlit as st

    st.markdown("### 📖 Школа Агентства W — инструкции по номерам")
    st.caption(
        "Один номер — одна задача. Инструкции доступны всем пользователям, "
        "даже без Неолы и независимо от материалов пригласившего Директора."
    )
    st.info(
        "📍 Вы здесь: " + INSTRUCTIONS_ROUTE
        + "\n\nНеола поможет голосом: «Открой инструкцию № 03 и подскажи первый шаг»."
    )
    query = st.text_input(
        "🔎 Найти инструкцию по номеру или теме",
        placeholder="Например: 01, Telegram, VK, первое сообщение",
        key="agency_w_builtin_instruction_search",
    )
    matches = find_instruction(query)
    if not matches:
        st.warning("Не нашла инструкцию по этому запросу. Попробуйте номер 01–07 или название темы.")
        return

    st.markdown("**Каталог:**")
    for guide in matches:
        st.markdown(f"**№ {guide['number']} — {guide['title']}**")

    for guide in matches:
        with st.expander(f"📘 № {guide['number']} — {guide['title']}", expanded=len(matches) == 1):
            st.write(guide["goal"])
            st.markdown("**Что нажимать:**")
            st.markdown("\n".join(
                f"{index}. {step}" for index, step in enumerate(guide["steps"], 1)
            ))
            st.success("Результат: " + guide["success"])
            st.caption("Если что-то не получается: " + guide["trouble"])
            st.caption("С Неолой: попросите «Помоги мне с инструкцией номер "
                       + guide["number"] + ", шаг один».")
