"""Единая политика качества кандидатов Неонии для всех социальных каналов.

Канал отвечает только за получение доступных публичных данных.
Решение "кандидат / не кандидат" принимается по общей бизнес-релевантности
и затем по паспорту ЦА текущего проекта.
"""

from __future__ import annotations
from typing import Any

BUSINESS_GATE_RULES = """
ЕДИНЫЙ ОБЯЗАТЕЛЬНЫЙ ФИЛЬТР НЕОНИИ ДЛЯ ЛЮБОЙ СОЦСЕТИ:

ПРИОРИТЕТНАЯ ЦА АГЕНТСТВА W — СЕТЕВИКИ:
люди, которые публично подтверждают участие в сетевом маркетинге / прямых продажах,
строят команду, ищут партнёров или клиентов, сопровождают новичков либо ведут
сетевой бизнес. Это главный сегмент для поиска партнёров Агентства W.

1. Сначала ищи и оценивай сетевиков. Сетевой бизнес должен подтверждаться
   конкретными публичными сведениями профиля, карьеры, описания деятельности
   или публикаций. Одного членства в сообществе недостаточно.

2. Для сетевика отмечай видимые задачи: поиск людей, переписка, follow-up,
   встречи и презентации, сопровождение команды, контент, заявки и напоминания.
   Не выдумывай интерес к ИИ или готовность стать партнёром.

3. Другие предприниматели, самозанятые и специалисты с повторяющейся рабочей
   рутиной — ДОПОЛНИТЕЛЬНЫЙ сегмент. Рассматривай их только после приоритетных
   сетевиков и помечай как дополнительный сегмент. Они не должны вытеснять
   подходящего сетевика из ежедневной пятёрки.

4. Для любого сегмента требуется конкретное публичное свидетельство реальной
   деятельности. Профессия или большая аудитория без делового контекста сами
   по себе недостаточны. Подписчики не доказывают потребность.

5. ИИ НЕ является положительным сигналом сам по себе.
   Если человек профессионально разрабатывает, внедряет, продаёт или обучает
   ИИ, нейросетям, AI-агентам, автоматизации, чат-ботам или AI-сервисам,
   это конкурент/поставщик, а НЕ текущая ЦА. Тогда:
   ai_provider_or_expert=true, business_relevant=false, score не выше 20;
   человека нельзя передавать Неоне в ежедневную пятёрку.

6. Обычное бытовое использование ChatGPT/ИИ не делает человека конкурентом,
   если его основная деятельность иная и ИИ не является его продуктом.

7. Не считать достаточным сигналом само по себе: мотивационные цитаты,
   поздравления, спорт, путешествия, лайфстайл, криптовалюту без рабочей задачи,
   развлекательный контент, одно присутствие в группе или общий интерес к технологиям.

8. Если в пуле достаточно подходящих сетевиков, все места пятёрки занимают они.
   Если после расширенного поиска их меньше пяти, разрешено заполнить оставшиеся
   места подходящими людьми дополнительного сегмента, но каждый такой профиль
   явно помечается «Дополнительный сегмент». Не снижай критерии и не выдавай
   вторичный сегмент за сетевиков.

9. Если данных недостаточно, не угадывай. Продолжай поиск и показывай фактический
   результат: цель 5/5, приоритет — подтверждённые сетевики, активность — не старше 48 часов.

10. Верни network_business_signal, automation_need_signal, business_evidence
    и business_gate_reason. Эти поля должны отражать только публичные факты.

Дополнительно верни:
- network_business_signal: true/false;
- ai_provider_or_expert: true/false;
- automation_need_signal: true/false;
- business_relevant: true/false;
- business_evidence: список 1–3 конкретных публичных свидетельств;
- business_gate_reason: короткая причина решения.
""".strip()


def apply_business_gate(
    item: dict[str, Any],
    score: int,
    *,
    pass_recommendation: str | None = None,
    reject_recommendation: str | None = None,
) -> tuple[int, str | None, list[str], str]:
    """Жёстко применяет бизнес-фильтр после ответа модели.

    Даже если модель дала высокий score, отсутствие подтвержденного
    бизнес-сигнала не позволяет человеку попасть в рекомендации.
    """
    score = max(0, min(100, int(score or 0)))

    relevant = item.get("business_relevant") is True
    network_signal = item.get("network_business_signal") is True
    ai_provider = item.get("ai_provider_or_expert") is True
    evidence = item.get("business_evidence")
    if isinstance(evidence, str):
        evidence = [evidence]
    if not isinstance(evidence, list):
        evidence = []
    evidence = [str(x).strip()[:300] for x in evidence if str(x).strip()][:3]

    reason = str(item.get("business_gate_reason") or "").strip()

    # Текущая ЦА шире сетевого бизнеса: обычные профессии и малый бизнес
    # тоже подходят, если есть реальная рутина, которую можно передать ИИ.
    if ai_provider:
        score = min(score, 20)
        return (
            score,
            reject_recommendation,
            evidence,
            reason or "Профессионально занимается ИИ/AI-автоматизацией — не текущая ЦА Агентства W.",
        )

    automation_need = item.get("automation_need_signal") is True

    if not relevant or not evidence:
        score = min(score, 39)
        if not reason:
            reason = "Нет подтверждённой практической релевантности."
        return score, reject_recommendation, evidence, reason

    if network_signal:
        # Сетевики — основной сегмент Агентства W и всегда идут первыми.
        score = max(score, 60)
        return score, pass_recommendation, evidence, reason or "Подтверждён основной сегмент: сетевой бизнес."

    if not automation_need:
        score = min(score, 49)
        return (
            score,
            reject_recommendation,
            evidence,
            reason or "Нет подтверждённой рутины для дополнительного сегмента.",
        )

    # Другие профессии можно показать только как дополнительный сегмент.
    # Потолок 59 гарантирует приоритет сетевиков (проходной балл 60+).
    score = min(max(score, 50), 59)
    return score, pass_recommendation, evidence, reason or "Дополнительный сегмент: подтверждена повторяющаяся рабочая рутина."
