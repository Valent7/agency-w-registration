"""Единая политика качества кандидатов Неонии для всех социальных каналов.

Канал отвечает только за получение доступных публичных данных.
Решение "кандидат / не кандидат" принимается по общей бизнес-релевантности
и затем по паспорту ЦА текущего проекта.
"""

from __future__ import annotations
from typing import Any

BUSINESS_GATE_RULES = """
ЕДИНЫЙ ОБЯЗАТЕЛЬНЫЙ ФИЛЬТР НЕОНИИ ДЛЯ ЛЮБОЙ СОЦСЕТИ:

1. Сначала проверь БИЗНЕС-РЕЛЕВАНТНОСТЬ человека текущему проекту.
   Только после этого сравнивай его с подробным портретом ЦА.

2. Для проекта, где ЦА связана с сетевым/партнёрским бизнесом, сильными
   публичными сигналами считаются, например:
   - прямое указание на сетевой маркетинг / MLM / прямые продажи;
   - построение команды, структуры, партнёрской сети;
   - поиск партнёров, лидеров, клиентов или людей в команду;
   - работа в партнёрской/реферальной модели;
   - предпринимательство, где явно нужен набор партнёров или развитие сети.

3. НЕ считать достаточным бизнес-сигналом само по себе:
   мотивационные цитаты, спорт, путешествия, красоту/лайфстайл, большое
   число подписчиков, коучинг без бизнес-контекста, криптовалюту без
   признаков партнёрской деятельности, развлекательный или знакомства-
   ориентированный контент.

4. Не делай моральных оценок человека и не делай выводов о его личной жизни.
   Если публичный контент просто не относится к бизнесу/ЦА, причина отказа:
   "нет подтверждённой бизнес-релевантности".

5. Если нет хотя бы одного конкретного публичного бизнес-сигнала:
   business_relevant=false, score не выше 39 и человека нельзя передавать
   Неоне как рекомендованного кандидата.

6. Если данных недостаточно, не угадывай. Такой профиль не попадает в TOP.
   Лучше выдать 3 качественных кандидата, чем заполнить список до 10 случайными.

7. TOP формируется только из людей, которые прошли бизнес-фильтр и затем
   соответствуют портрету ЦА проекта. Канал (Telegram, VK, Instagram,
   LinkedIn или будущий источник) не меняет это правило.

Дополнительно к обычным полям верни:
- business_relevant: true/false;
- business_evidence: список 1–3 конкретных публичных свидетельств;
- business_gate_reason: короткая причина решения.
""".strip()


def apply_business_gate(
    item: dict[str, Any],
    score: int,
    *,
    pass_recommendation: str | None = None,
    reject_recommendation: str | None = None,
) -> tuple[int, str | None, list[str], str]:
    """Жёстко применяет бизнес-фильтр после ответа модели.

    Даже если модель дала высокий score, отсутствие подтвержденного
    бизнес-сигнала не позволяет человеку попасть в рекомендации.
    """
    score = max(0, min(100, int(score or 0)))

    relevant = item.get("business_relevant") is True
    evidence = item.get("business_evidence")
    if isinstance(evidence, str):
        evidence = [evidence]
    if not isinstance(evidence, list):
        evidence = []
    evidence = [str(x).strip()[:300] for x in evidence if str(x).strip()][:3]

    reason = str(item.get("business_gate_reason") or "").strip()
    if not relevant or not evidence:
        score = min(score, 39)
        recommendation = reject_recommendation
        if not reason:
            reason = "Нет подтверждённой бизнес-релевантности."
        return score, recommendation, evidence, reason

    return score, pass_recommendation, evidence, reason
