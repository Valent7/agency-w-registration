"""Единая политика качества кандидатов Неонии для всех социальных каналов.

Канал отвечает только за получение доступных публичных данных.
Решение "кандидат / не кандидат" принимается по общей бизнес-релевантности
и затем по паспорту ЦА текущего проекта.
"""

from __future__ import annotations
from typing import Any

BUSINESS_GATE_RULES = """
ЕДИНЫЙ ОБЯЗАТЕЛЬНЫЙ ФИЛЬТР НЕОНИИ ДЛЯ ЛЮБОЙ СОЦСЕТИ:

АКТУАЛЬНАЯ ЦА АГЕНТСТВА W:
человек из сетевого/партнёрского бизнеса, прямых продаж или реферальной модели,
который строит команду/структуру, ищет партнёров/клиентов, ведёт много переписки,
встреч, сопровождения и контента, но САМ НЕ ЯВЛЯЕТСЯ специалистом или продавцом
решений в области ИИ/нейросетей/AI-агентов/автоматизации. Ему ИИ нужен как
понятный инструмент, который снимет ручную рутину и вернёт время.

1. Сначала проверь ПРАКТИЧЕСКУЮ РЕЛЕВАНТНОСТЬ человека этой ЦА,
   затем сравни его с подробным портретом ЦА владельца.

2. ОБЯЗАТЕЛЬНЫЙ положительный сигнал — публичное подтверждение хотя бы одного:
   - сетевой маркетинг / MLM / прямые продажи / партнёрская или реферальная модель;
   - построение команды, структуры, ветки, поиск партнёров, лидеров или клиентов;
   - управление партнёрами/командой с регулярной коммуникацией и сопровождением.

3. Сильные дополнительные сигналы:
   - ручной рекрутинг, поиск людей, переписка, follow-up;
   - организация встреч, презентаций, сопровождение новичков;
   - регулярный контент и ведение соцсетей;
   - нехватка времени, перегруз, повторяющиеся ручные действия;
   - таблицы, CRM, списки, заявки, напоминания и другая административная рутина.

4. ИИ НЕ является положительным сигналом сам по себе.
   Если человек профессионально разрабатывает, внедряет, продаёт или обучает:
   ИИ, нейросетям, AI-агентам, автоматизации, чат-ботам или AI-сервисам,
   это наш конкурент/поставщик, а НЕ текущая ЦА.
   В таком случае:
   ai_provider_or_expert=true,
   business_relevant=false,
   score не выше 20,
   человека нельзя передавать Неоне в ежедневную пятёрку.

5. Обычное бытовое использование ChatGPT/ИИ не делает человека конкурентом,
   если его основная деятельность — сетевой/партнёрский бизнес и он не продаёт
   собственные AI-услуги/обучение/агентов/автоматизацию.

6. Не считать достаточным сигналом само по себе:
   мотивационные цитаты, поздравления, спорт, путешествия, лайфстайл,
   большое число подписчиков, криптовалюту без рабочей задачи, развлекательный
   контент, одно лишь присутствие в группе или общий интерес к технологиям.

7. Если нет подтверждения сетевого/партнёрского контекста:
   network_business_signal=false, business_relevant=false, score не выше 39,
   человека не передавать Неоне как рекомендованного кандидата.

8. Если нет конкретной рабочей рутины/задачи, которую может облегчить ИИ,
   снижай оценку и не называй человека приоритетным.

9. Если данных недостаточно, не угадывай. Продолжай искать глубже по источнику,
   пока не исчерпан разумный объём публичных данных. Цель — найти до 5
   качественных людей, а не первые 5 технически подходящих профилей.

10. TOP формируется только из людей, которые прошли этот фильтр и затем
    соответствуют портрету ЦА проекта.

Дополнительно к обычным полям верни:
- network_business_signal: true/false;
- ai_provider_or_expert: true/false;
- automation_need_signal: true/false;
- business_relevant: true/false;
- business_evidence: список 1–3 конкретных публичных свидетельств;
- business_gate_reason: короткая причина решения.
""".strip()


def apply_business_gate(
    item: dict[str, Any],
    score: int,
    *,
    pass_recommendation: str | None = None,
    reject_recommendation: str | None = None,
) -> tuple[int, str | None, list[str], str]:
    """Жёстко применяет бизнес-фильтр после ответа модели.

    Даже если модель дала высокий score, отсутствие подтвержденного
    бизнес-сигнала не позволяет человеку попасть в рекомендации.
    """
    score = max(0, min(100, int(score or 0)))

    relevant = item.get("business_relevant") is True
    network_signal = item.get("network_business_signal") is True
    ai_provider = item.get("ai_provider_or_expert") is True
    evidence = item.get("business_evidence")
    if isinstance(evidence, str):
        evidence = [evidence]
    if not isinstance(evidence, list):
        evidence = []
    evidence = [str(x).strip()[:300] for x in evidence if str(x).strip()][:3]

    reason = str(item.get("business_gate_reason") or "").strip()

    # Текущая ЦА: сетевой/партнёрский бизнес, но не профессиональный AI-рынок.
    if ai_provider:
        score = min(score, 20)
        return (
            score,
            reject_recommendation,
            evidence,
            reason or "Профессионально занимается ИИ/AI-автоматизацией — не текущая ЦА Агентства W.",
        )

    if not network_signal:
        score = min(score, 39)
        return (
            score,
            reject_recommendation,
            evidence,
            reason or "Не подтверждён сетевой/партнёрский бизнес — не текущая ЦА.",
        )

    if not relevant or not evidence:
        score = min(score, 39)
        recommendation = reject_recommendation
        if not reason:
            reason = "Нет подтверждённой практической релевантности."
        return score, recommendation, evidence, reason

    return score, pass_recommendation, evidence, reason
