"""Единая политика качества кандидатов Неонии для всех социальных каналов.

Канал отвечает только за получение доступных публичных данных.
Решение "кандидат / не кандидат" принимается по общей бизнес-релевантности
и затем по паспорту ЦА текущего проекта.
"""

from __future__ import annotations
from typing import Any

BUSINESS_GATE_RULES = """
ЕДИНЫЙ ОБЯЗАТЕЛЬНЫЙ ФИЛЬТР НЕОНИИ ДЛЯ ЛЮБОЙ СОЦСЕТИ:

1. Сначала проверь ПРАКТИЧЕСКУЮ РЕЛЕВАНТНОСТЬ человека Агентству W,
   затем сравни его с подробным портретом ЦА владельца.

2. Главный ориентир Агентства W — человек, которому полезно передать
   повседневную рутину ИИ, чтобы освободить время для жизни, семьи,
   отдыха, прогулок и более важной человеческой работы.
   Профессия, возраст, прежний интерес к MLM или криптовалюте сами по себе
   не являются главным критерием.

3. Конкретными публичными сигналами релевантности могут быть:
   - предпринимательство, самозанятость, консультации, продажи, работа с клиентами;
   - управление командой, партнёрами, сообществом, проектом или большим потоком людей;
   - рекрутинг, поиск клиентов/партнёров, организация встреч и сопровождение;
   - регулярное создание контента, продвижение, ведение соцсетей;
   - жалобы на нехватку времени, перегруз, повторяющиеся ручные задачи или рутину;
   - интерес к ИИ, автоматизации, цифровым помощникам, нейросетям и новым инструментам;
   - обучение/работа, где заметно много повторяющейся коммуникационной или административной работы;
   - активное содержательное участие в деловом/предпринимательском сообществе,
     если конкретное публичное сообщение показывает рабочую, проектную или организационную задачу.

4. Для сетевого/партнёрского бизнеса дополнительными сильными сигналами остаются:
   построение команды/структуры, поиск партнёров/лидеров/клиентов,
   партнёрская или реферальная модель. Но это НЕ обязательное условие.

5. Не считать достаточным сигналом само по себе:
   мотивационные цитаты, поздравления, спорт, путешествия, красоту/лайфстайл,
   большое число подписчиков, криптовалюту без рабочей задачи, развлекательный
   контент или одно лишь присутствие в группе.

6. Не делай моральных оценок человека и не делай выводов о его личной жизни.
   Если публичные данные не показывают реальной рабочей/проектной задачи,
   которую мог бы облегчить ИИ, укажи: "нет подтверждённой практической релевантности".

7. Если нет хотя бы одного конкретного публичного сигнала:
   business_relevant=false, score не выше 39 и человека нельзя передавать
   Неоне как рекомендованного кандидата.

8. Если данных недостаточно, не угадывай. При этом продолжай искать глубже
   по источнику, пока не исчерпан разумный объём публичных данных. В большой
   выбранной группе цель — найти до 5 качественных людей, а не остановиться
   после первых 20–30 авторов.

9. TOP формируется только из людей, которые прошли этот фильтр и затем
   соответствуют портрету ЦА проекта. Канал не меняет это правило.

Дополнительно к обычным полям верни:
- business_relevant: true/false;
- business_evidence: список 1–3 конкретных публичных свидетельств;
- business_gate_reason: короткая причина решения.
""".strip()


def apply_business_gate(
    item: dict[str, Any],
    score: int,
    *,
    pass_recommendation: str | None = None,
    reject_recommendation: str | None = None,
) -> tuple[int, str | None, list[str], str]:
    """Жёстко применяет бизнес-фильтр после ответа модели.

    Даже если модель дала высокий score, отсутствие подтвержденного
    бизнес-сигнала не позволяет человеку попасть в рекомендации.
    """
    score = max(0, min(100, int(score or 0)))

    relevant = item.get("business_relevant") is True
    evidence = item.get("business_evidence")
    if isinstance(evidence, str):
        evidence = [evidence]
    if not isinstance(evidence, list):
        evidence = []
    evidence = [str(x).strip()[:300] for x in evidence if str(x).strip()][:3]

    reason = str(item.get("business_gate_reason") or "").strip()
    if not relevant or not evidence:
        score = min(score, 39)
        recommendation = reject_recommendation
        if not reason:
            reason = "Нет подтверждённой бизнес-релевантности."
        return score, recommendation, evidence, reason

    return score, pass_recommendation, evidence, reason
