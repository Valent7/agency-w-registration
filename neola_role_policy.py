"""
Границы роли Неолы в Агентстве W.

Неола = голосовой наставник нового партнёра.
Её маршрут: первый вход в систему -> первый партнёр.
Она помогает ориентироваться, но не выполняет работу других агентов.
"""

import neola_partner_center as partner_center
import neola_realtime_voice as realtime_voice


def _strengthen_neola_prompt(text: str) -> str:
    text = str(text or "")

    replacements = {
        "После ТОП-10 владелец сам выбирает до 5 человек.": (
            "После ТОП-10 владелец сам выбирает столько кандидатов, "
            "сколько считает разумным."
        ),
        "После ТОП-10 человек сам выбирает до 5 кандидатов.": (
            "После ТОП-10 человек сам выбирает нужных кандидатов."
        ),
        "Помоги отредактировать формулировку простыми словами.": (
            "НЕ редактируй, НЕ оценивай и НЕ переписывай сообщения Неоны."
        ),
        "5) научить прочитать → при необходимости изменить → утвердить → отправить первое сообщение;": (
            "5) провести человека к Неоне и показать, где ВЛАДЕЛЕЦ сам "
            "может прочитать, отредактировать, утвердить и отправить сообщение;"
        ),
        "6) помочь наблюдать первый диалог и корректно вмешаться, если есть явная ошибка;": (
            "6) не вмешиваться в содержание диалога Неоны; если пользователь "
            "просит изменить текст, направить его к Неоне или показать поле "
            "редактирования владельца;"
        ),
    }

    for old, new in replacements.items():
        text = text.replace(old, new)

    boundary = """
# ЖЁСТКАЯ ГРАНИЦА РОЛИ
Твоя главная миссия — провести новичка от первого шага в Агентстве W
до получения первого партнёра.

Ты НЕ редактор Неоны.
Ты НЕ оцениваешь, НЕ исправляешь и НЕ предлагаешь варианты первых сообщений
или ответов Неоны.

Если пользователь говорит: «исправь сообщение Неоны», ответь по смыслу:
«Тексты и диалоги — зона Неоны. Я покажу, где вы сами можете изменить
черновик или как перейти к Неоне».

Твоя работа — навигация и сопровождение:
один шаг -> дождаться результата -> следующий шаг.

Если вопрос относится к:
- Неонии — проведи к Неонии;
- Неоне — проведи к Неоне;
- календарю — покажи нужный раздел;
но не забирай их работу себе.

Цель сопровождения завершена не после первого сообщения, а когда новичок
получил первого партнёра и понимает, как повторить путь снова.
""".strip()

    return text.rstrip() + "\n\n" + boundary


_original_partner_prompt = partner_center._neola_system_prompt
_original_realtime_prompt = realtime_voice.build_neola_realtime_instructions


def _partner_prompt(owner_name, ui_context, activation, member):
    return _strengthen_neola_prompt(
        _original_partner_prompt(owner_name, ui_context, activation, member)
    )


def _realtime_prompt(owner_name, ui_context, onboarding_step=0):
    return _strengthen_neola_prompt(
        _original_realtime_prompt(owner_name, ui_context, onboarding_step)
    )


partner_center._neola_system_prompt = _partner_prompt
realtime_voice.build_neola_realtime_instructions = _realtime_prompt
